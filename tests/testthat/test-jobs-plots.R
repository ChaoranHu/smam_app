test_that("a background job runs, reports its result and logs", {
  d <- sim_track("MR", n = 40)
  job <- start_job("fit", fit_spec("MR", d, list(likelihood = "full")), "test fit")
  expect_true(job_running(job) || !job$proc$is_alive())
  job$proc$wait(120000)
  res <- job_result(job)
  expect_true(res$ok)
  expect_length(res$value$estimate, 3)
  expect_type(job_log_tail(job), "character")
})

test_that("a failing job returns its error message, and a job can be cancelled", {
  bad <- start_job("fit", fit_spec("MR", data.frame(time = 1:3), list(likelihood = "full")), "bad")
  bad$proc$wait(60000)
  res <- job_result(bad)
  expect_false(res$ok)
  expect_true(nzchar(res$error))
  d <- sim_track("MRME", n = 200, Tend = 200)
  slow <- start_job("fit", fit_spec("MRME", d, c(list(variant = "exact"), mrme_bounds())), "slow")
  Sys.sleep(1)
  expect_true(job_running(slow))
  cancel_job(slow)
  Sys.sleep(1)
  expect_false(job_running(slow))
  expect_false(job_running(NULL))
})

test_that("time is formatted for people", {
  expect_equal(format_seconds(5.4), "5 s")
  expect_equal(format_seconds(125), "2 min 05 s")
})

test_that("every figure builds", {
  build <- function(p) expect_silent(ggplot2::ggplot_build(p))
  d <- sim_track("MR", n = 30)
  build(plot_track(d, "time"))
  build(plot_coords(d))
  build(plot_steps(d))
  d$segment <- rep(c(0, 1, 2), each = 10)
  build(plot_track(d, "segment"))
  st <- rep(c("moving", "resting"), 15)
  build(plot_track(d, "state", st))
  build(plot_track(d, "state", st, state_title = "True state"))
  build(plot_state_path(data.frame(time = d$time), st))
  one <- data.frame(time = 1:10, X1 = cumsum(rnorm(10)))
  build(plot_track(one, "time"))
  many <- sim_track("MR", n = 30)
  many$segment <- rep(1:10, each = 3)
  build(plot_track(many, "segment"))
  three <- data.frame(time = 1:10, p.m = 0.2, p.r = 0.3, p.h = 0.5)
  build(plot_state_prob(three, c("moving", "resting", "handling")))
})
